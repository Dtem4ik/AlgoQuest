/** Случайная реплика. Вызывать в обработчиках событий, а не во время рендера. */
export function pickMascotLine(state: MascotState, random: () => number = Math.random): string {
  const lines = MASCOT_LINES[state];
  return lines[Math.floor(random() * lines.length)] ?? lines[0] ?? "";
}
